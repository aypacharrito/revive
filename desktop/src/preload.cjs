'use strict';
const { contextBridge, ipcRenderer } = require('electron');
const invoke = (channel, ...args) => ipcRenderer.invoke(channel, ...args);
contextBridge.exposeInMainWorld('revive', Object.freeze({
  listGames: () => invoke('library:list'),
  catalogList: () => invoke('catalog:list'),
  catalogDownload: id => invoke('catalog:download',id),
  openSupport: () => invoke('support:open'),
  socialStatus: () => invoke('social:status'),
  socialPresence: ids => invoke('social:presence',ids),
  connectionStatus: () => invoke('cloud:connectionStatus'),
  socialSignUp: (email,password) => invoke('social:signup',email,password),
  socialSignIn: (email,password) => invoke('social:signin',email,password),
  socialSignOut: () => invoke('social:signout'),
  socialProfile: (handle,display) => invoke('social:profile',handle,display),
  socialInvite: handle => invoke('social:invite',handle),
  socialRespond: (id,accept) => invoke('social:respond',id,accept),
  socialMessages: id => invoke('social:messages',id),
  socialSend: (id,body) => invoke('social:send',id,body),
  updateStatus: () => invoke('updates:status'),
  checkUpdates: () => invoke('updates:check'),
  installUpdate: () => invoke('updates:install'),
  onUpdateState: fn => ipcRenderer.on('updates:state', (_event, data) => fn(data)),
  emulatorStatus: () => invoke('emulation:status'),
  gpuStatus: () => invoke('emulation:gpu'),
  configureEmulator: id => invoke('emulation:chooseEngine',id),
  configureCore: id => invoke('emulation:chooseCore',id),
  importConsole: platform => invoke('emulation:import',platform),
  gameProfile: id => invoke('library:profile', id),
  checkNetwork: () => invoke('multiplayer:networkCheck'),
  toggleFavorite: id => invoke('library:favorite',id),
  selectArtwork: id => invoke('library:artwork',id),
  artworkData: id => invoke('library:artworkData',id),
  startDownload: descriptor => invoke('download:start',descriptor),
  cancelDownload: id => invoke('download:cancel',id),
  openDownloads: () => invoke('download:folder'),
  selectSource: () => invoke('source:select'),
  reviewSource: () => invoke('source:review'),
  onDownloadChanged: fn => ipcRenderer.on('download:changed', (_event,data)=>fn(data)),
  onGameSession: fn => ipcRenderer.on('game:session',(_event,data)=>fn(data)),
  importExe: () => invoke('library:chooseExe'),
  scanFolder: () => invoke('library:scanFolder'),
  importCandidate: exe => invoke('library:addCandidate', exe),
  removeGame: id => invoke('library:remove', id),
  renameGame: (id, name) => invoke('library:rename', id, name),
  inspectGame: id => invoke('library:inspect', id),
  launchGame: id => invoke('library:play', id),
  reveal: id => invoke('library:reveal', id),
  pickSaveDir: id => invoke('save:chooseDirectory', id),
  listBackups: id => invoke('save:list', id),
  backup: id => invoke('save:backup', id),
  restore: (id, name) => invoke('save:restore', id, name),
  cloudUpload: id => invoke('cloud:upload', id),
  cloudRestore: id => invoke('cloud:restore', id),
  settings: () => invoke('settings:get'),
  saveSettings: settings => invoke('settings:save', settings),
  aiDiagnose: id => invoke('ai:diagnose', id),
  onLibraryChanged: fn => { ipcRenderer.on('library:changed', fn); }
}));
